#!/usr/bin/env python3
"""Reproduce the WGSL port of the pinned Anime4K 3D US CNN weights.

No network, model training or build-time Python dependency is required.
The GLSL source is retained for provenance and independent verification.
"""

import argparse
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "assets/models/anime4k-3d-x2-us.glsl"
OUTPUT = ROOT / "src/gpu/neural.wgsl"


def generate(source):
    header = source.split("//!DESC", 1)[0]
    blocks = re.findall(r"vec4 hook\(\) \{\n(.*?)\n\}", source, re.S)
    if len(blocks) != 4:
        raise ValueError("Expected exactly three convolutions and one depth-to-space pass")
    shader = header + """// Generated by scripts/generate-neural-shader.py. Do not edit weights by hand.
// Source: bloc97/Anime4K, 7684e9586f8dcc738af08a1cdceb024cc184f426.
// Signed feature maps use RGBA16Float. Matrices retain GLSL column order.
@group(0) @binding(0) var features: texture_2d<f32>;
@group(0) @binding(1) var original: texture_2d<f32>;
@group(0) @binding(2) var linear_sampler: sampler;
struct Vertex { @builtin(position) position: vec4<f32>, @location(0) uv: vec2<f32> }
@vertex fn vs_main(@builtin(vertex_index) index: u32) -> Vertex {
    let uv = vec2<f32>(f32((index << 1u) & 2u), f32(index & 2u));
    return Vertex(vec4<f32>(uv * vec2<f32>(2.0, -2.0) + vec2<f32>(-1.0, 1.0), 0.0, 1.0), uv);
}
fn sample_raw(p: vec2<i32>, offset: vec2<i32>) -> vec4<f32> {
    return textureLoad(features, clamp(p + offset, vec2<i32>(0), vec2<i32>(textureDimensions(features)) - 1), 0);
}
fn sample_positive(p: vec2<i32>, offset: vec2<i32>) -> vec4<f32> {
    return max(sample_raw(p, offset), vec4<f32>(0.0));
}
fn sample_negative(p: vec2<i32>, offset: vec2<i32>) -> vec4<f32> {
    return max(-sample_raw(p, offset), vec4<f32>(0.0));
}
"""
    matrix_count = 0

    def matrix(match):
        nonlocal matrix_count
        values = [v.strip() for v in match[1].split(",")]
        if len(values) != 16:
            raise ValueError("Expected 16 matrix coefficients")
        matrix_count += 1
        columns = ["vec4<f32>(" + ", ".join(values[i:i + 4]) + ")" for i in range(0, 16, 4)]
        return "mat4x4<f32>(" + ", ".join(columns) + ")"

    for layer, body in enumerate(blocks[:3]):
        body = re.sub(r"mat4\(([^)]+)\)", matrix, body)
        body = body.replace("vec4 result =", "var result =").replace("vec4(", "vec4<f32>(")
        for activation in range(2):
            sample = "sample_raw" if layer == 0 else "sample_positive" if activation == 0 else "sample_negative"
            body = re.sub(
                rf"go_{activation}\((-?\d+)\.0, (-?\d+)\.0\)",
                rf"{sample}(p, vec2<i32>(\1, \2))",
                body,
            )
        shader += f"\n@fragment fn conv{layer}(v: Vertex) -> @location(0) vec4<f32> {{\n"
        shader += "    let p = vec2<i32>(v.position.xy);\n" + body + "\n}\n"
    if matrix_count != 36 or "go_" in shader:
        raise ValueError("Unexpected model structure")
    shader += """
@fragment fn reconstruct(v: Vertex) -> @location(0) vec4<f32> {
    let p = vec2<u32>(v.position.xy);
    let residual = textureLoad(features, vec2<i32>(p / 2u), 0)[(p.y % 2u) * 2u + p.x % 2u];
    let base = textureSampleLevel(original, linear_sampler, v.uv, 0.0);
    // The learned residual affects luminance equally in RGB; retain source alpha.
    return vec4<f32>(base.rgb + vec3<f32>(residual), base.a);
}
"""
    return shader


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    shader = generate(SOURCE.read_text())
    if args.check:
        if OUTPUT.read_text() != shader:
            raise SystemExit("neural.wgsl differs from the pinned model; regenerate it")
    else:
        OUTPUT.write_text(shader)


if __name__ == "__main__":
    main()
